    Function = { fg = 0xc1f29d },
    Keyword = { fg = 0x69e598, bold = true },
    Statement = { fg = 0x69e598 },
    Conditional = { fg = 0x69e598 },
    Repeat = { fg = 0x69e598 },
    Type = { fg = 0x7ee0bf },
    Identifier = { fg = 0xc5d5cd },
    Constant = { fg = 0xd7dfa6 },
    Number = { fg = 0xe0be79 },
    Boolean = { fg = 0xe0be79 },
    Operator = { fg = 0x78b79a },
    Special = { fg = 0x7bdac6 },
    PreProc = { fg = 0x7ee0bf },
    Delimiter = { fg = 0x94ad9f },
    Directory = { fg = 0x69e598 },
    LineNr = { fg = 0x4c6657 },
